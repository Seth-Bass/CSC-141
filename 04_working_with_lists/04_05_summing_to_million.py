# Create a list of numbers from 1 to 1 million
numbers = range(1, 1000001)

# Use min() to check the first number and max() to check the last number
print("The minimum number is:", min(numbers))
print("The maximum number is:", max(numbers))

# Use sum() to calculate the sum of all the numbers
total_sum = sum(numbers)
print("The sum of numbers from 1 to 1 million is:", total_sum)
